from app.reviewers.base import BaseReviewer, ReviewerOutput


class MockReviewer(BaseReviewer):
    """Deterministic demo reviewer. This is not an AI model."""
    name = "mock"

    def review(self, sample: dict) -> ReviewerOutput:
        # Dataset contains explicit demo predictions so offline runs are repeatable.
        findings = []
        for category in sample.get("mock_detected_categories", []):
            findings.append({
                "sample_id": sample["id"],
                "source": self.name,
                "category": category,
                "severity": "medium",
                "message": f"Demonstration finding for category '{category}'. Verify against source.",
                "line": None,
            })
        return ReviewerOutput(True, findings, "Deterministic demo output; not generated by an LLM.")
